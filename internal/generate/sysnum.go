package generate

import (
	"bufio"
	"fmt"
	"io"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

// Syscall numbers for the raw_syscalls dispatch (task 8e4,
// internal/c/dispatch.c): its program arrays are indexed by the running
// arch's syscall number, the generated handlers are named after the
// tracepoint. golang.org/x/sys/unix's zsysnum_linux_<arch>.go is the
// number source - pinned by go.mod, so the table does not depend on the
// generation host's kernel headers, and one file per arch.

// sysnumRe matches one constant of x/sys's zsysnum_linux_<arch>.go.
var sysnumRe = regexp.MustCompile(`^\s*SYS_([A-Z0-9_]+)\s*=\s*(\d+)\s*$`)

// syscallAliases maps a tracepoint's syscall name to the name its number
// has where the two differ: the tracepoint is named after the kernel's
// SYSCALL_DEFINE (sys_newuname), the number after the table entry (uname).
var syscallAliases = map[string]string{
	"newfstat":     "fstat",
	"newlstat":     "lstat",
	"newstat":      "stat",
	"newuname":     "uname",
	"sendfile64":   "sendfile",
	"umount":       "umount2",
	"fadvise64_64": "fadvise64", // arm64
}

// SyscallNumbers is the rendered table of one arch.
type SyscallNumbers struct {
	// Source is the Go file content.
	Source string
	// Unresolved are the syscalls of the generated handlers that have no
	// number on this arch, left out of the table.
	Unresolved []string
}

// GenerateSyscallNumbersGo renders internal/bpf/sysnum_<goarch>.go: the
// number of every syscall the generated C (cSource) has handlers for,
// taken from zsysnum, the x/sys file of that arch (origin names it in the
// header).
func GenerateSyscallNumbersGo(cSource, zsysnum io.Reader, goarch, origin string) (SyscallNumbers, error) {
	numbers, err := parseSysnum(zsysnum)
	if err != nil {
		return SyscallNumbers{}, err
	}
	tracepoints, err := extractTracepoints(cSource)
	if err != nil {
		return SyscallNumbers{}, err
	}
	table := map[string]int{}
	var unresolved []string
	for _, tp := range tracepoints {
		name, ok := strings.CutPrefix(tp, "sys_enter_")
		if !ok {
			continue
		}
		nr, ok := numbers[sysnumName(name)]
		if !ok {
			unresolved = append(unresolved, name)
			continue
		}
		table[name] = nr
	}
	sort.Strings(unresolved)
	return SyscallNumbers{Source: formatSysnumGo(table, goarch, origin), Unresolved: unresolved}, nil
}

// sysnumName is the number's name of a tracepoint's syscall name.
func sysnumName(name string) string {
	if alias, ok := syscallAliases[name]; ok {
		return alias
	}
	return name
}

// parseSysnum reads the SYS_* constants, lowercased, with their numbers.
func parseSysnum(r io.Reader) (map[string]int, error) {
	numbers := map[string]int{}
	scanner := bufio.NewScanner(r)
	for scanner.Scan() {
		m := sysnumRe.FindStringSubmatch(scanner.Text())
		if m == nil {
			continue
		}
		nr, err := strconv.Atoi(m[2])
		if err != nil {
			return nil, fmt.Errorf("syscall number of SYS_%s: %w", m[1], err)
		}
		numbers[strings.ToLower(m[1])] = nr
	}
	if err := scanner.Err(); err != nil {
		return nil, fmt.Errorf("scanning syscall numbers: %w", err)
	}
	if len(numbers) == 0 {
		return nil, fmt.Errorf("no SYS_ constants in the syscall number source")
	}
	return numbers, nil
}

// formatSysnumGo renders the table sorted by name.
func formatSysnumGo(table map[string]int, goarch, origin string) string {
	names := make([]string, 0, len(table))
	for name := range table {
		names = append(names, name)
	}
	sort.Strings(names)
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by mage generateSyscallNumbersGo from %s. DO NOT EDIT.\n\n", origin)
	b.WriteString("package bpf\n\n")
	fmt.Fprintf(&b, "// syscallNumbers maps the generated handlers' syscalls to their %s\n", goarch)
	b.WriteString("// numbers, the slots of dispatch.c's program arrays.\n")
	b.WriteString("var syscallNumbers = map[string]uint32{\n")
	for _, name := range names {
		fmt.Fprintf(&b, "\t%q: %d,\n", name, table[name])
	}
	b.WriteString("}\n")
	return b.String()
}
