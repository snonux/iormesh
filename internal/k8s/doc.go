// Package k8s is iormesh's Kubernetes side (docs/milestones.md M7, decisions
// #12, #13, #14, #18 and #21; docs/implementation.md M7 steps 5, 6, 8 and 9):
// the Kubectl transport, which reaches a tracer container in a pod
// through the operator's kubectl the way federate.SSH reaches a server
// through the operator's ssh, the tracer half of its trace fetch, the
// manifests that prepare a pod, and pod identity.
//
//   - target.go: what one pod session is (context, namespace, pod, app
//     container, image, mode, profile), how flags, the pod entry, the
//     cluster and the defaults layer into it (#18's precedence), and the
//     checks every value passes before it reaches a kubectl argv: a
//     context the registry lists, an image pinned by digest, Kubernetes
//     names only.
//   - kubectl.go: the Transport — Run is `kubectl exec`, Fetch an
//     exec-streamed tar of the project's ready/ segments, Push refused
//     (the image carries the tracer; #12 rules out `kubectl cp`).
//   - debug.go: `kubectl debug --target`, the ephemeral tracer container,
//     created only in a pod already prepared with #13's two volumes.
//   - deploy.go: iormeshctl deploy's step for one pod — start the debug
//     container, or accept a tracer container already there (sidecar or
//     earlier debug container) only if its status imageID is the pinned
//     digest (task af4), or start the next debug tracer in place of
//     ended ones (task ah4).
//   - tracers.go: a debug pod's successive tracers — "iormesh",
//     "iormesh-2" … up to MaxDebugTracers — since a debug tracer dies
//     with its app container and an ephemeral container is never
//     restarted, removed or renamed (task ah4).
//   - pods.go: which running pods a registry pods: entry is (a named pod
//     or a label selector), with each pod's UID — its store directory and
//     host identity — and whether a tracer container is in it.
//   - lock.go: one fetch at a time into a local directory.
//   - ready.go: both ends of the fetch stream — the tracer's
//     `iormesh ready` writer (cgo-free, so internal/cli wires it in) and
//     the controller's unpacker, which trusts nothing in the stream.
//   - manifest.go, manifest_spec.go: deploy/'s prepare patch, sidecar
//     patch and --custom profile, generated by `mage k8sManifests`
//     (steps 5 and 8); the sidecar's container is customSpec's.
//   - cgroup.go: a process's pod UID and container id from its
//     /proc/<pid>/cgroup, for either kubelet cgroup driver (step 6).
//   - pod.go: the tracer's side — its pod from the downward API, and
//     the project it defaults to, the namespace (decision #21). Pod
//     names are resolved on the controller (step 7), never by a tracer.
//
// No call ever goes through a shell: kubectl gets an argv, and
// `kubectl exec … -- argv` hands the container runtime an argv too, so
// pod or container names cannot inject anything; they are checked
// against Kubernetes' own name rules regardless (internal/k8sname's,
// shared with internal/federate, which checks the registry's k8s: and
// pods: sections), and every value goes in `--flag=value` form so none
// can read as an option.
//
// The package is cgo-free: iormeshctl runs on a laptop (CGO_ENABLED=0).
