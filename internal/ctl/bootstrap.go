// `iormeshctl bootstrap [-apply] HOST` (docs/decisions.md #1, task
// qh4): the first install of the tracer on a registered host — the one step
// deploy cannot take, since deploy only upgrades through the sudoers rule
// and the rule does not exist yet. It takes the operator's own sudo once.
//
// Without -apply it contacts nothing and prints the exact steps for the
// arch and SSH user -arch and -user name, to run by hand on a terminal,
// where sudo may ask for a password. With -apply it runs the same steps
// (bootstrapSteps, one list for both) over the Transport. That Transport
// has no TTY (ssh BatchMode, decision #12), so an interactive sudo cannot
// work there: -apply runs every privileged step as `sudo -n` and refuses
// a host whose sudo wants a password, pointing at the printed steps.
//
// Trust: the controller verifies dist/iormesh-linux-<arch> against its
// pinned key exactly as deploy does (release.ReadVerified) and stages the
// very bytes it verified. Root installs each file under a temporary name
// in its target directory, checks that root-owned copy's SHA-256 against
// the controller's (the rule also with visudo -cf) and only then renames
// it into place, so the binary never runs, and the rule never applies,
// before the check. Before the rule goes live the installed tracer's own
// `upgrade` of the staged build re-verifies it against the root-owned key
// and checks the layout (/opt and the tree root's, nothing writable by
// others); the rule, generated by internal/hostlayout, comes last, and a
// `sudo -n iormesh status` proves it. A host that already has
// /etc/sudoers.d/iormesh is refused: bootstrap never overwrites a rule.

const (
	// hashCheck runs as `sh -c hashCheck sh FILE SUM` under sudo: it
	// fails unless FILE's SHA-256 is SUM. sha256sum reads stdin, so its
	// output is "SUM  -" whatever FILE is called.
	hashCheck = `test "$(sha256sum < "$1")" = "$2  -"`
	// stagedKey and stagedRule are the staged names of the pinned key
	// and the rule, next to the build in the staging directory.
	stagedKey  = "minisign.pub"
	stagedRule = "iormesh.sudoers"
	// defaultBootstrapArch is the printed steps' arch without -arch.
	defaultBootstrapArch = "amd64"
	// printedStaging is the staging directory as the printed steps name
	// it on the host: the shell expands ~ before sudo sees the path.
	printedStaging = "~/" + stagingRel
)

// bootstrapFlags are bootstrap's parsed command line.
type bootstrapFlags struct {
	regPath, dist, keyPath, arch, user, host string
	apply                                    bool
}

// bootstrapCommand parses bootstrap's flags, refuses an unregistered
// host before anything else (the registry is the deploy boundary), then
// prints the steps or, with -apply, runs them under the host's deadline.
func bootstrapCommand(args []string, e env) error {
	f, err := parseBootstrapFlags(args, e)
	if err != nil {
		return err
	}
	r, err := loadRegistry(f.regPath, e)
	if err != nil {
		return err
	}
	if _, err := r.Lookup(f.host); err != nil {
		return fmt.Errorf("%w (iormeshctl add it first)", err)
	}
	key, err := pinnedKey(f.keyPath, e)
	if err != nil {
		return err
	}
	if !f.apply {
		return printBootstrap(e, f, key)
	}
	return e.onHost(e.root(), func(ctx context.Context) error {
		if err := applyBootstrap(ctx, e, f, key); err != nil {
			return fmt.Errorf("%s: %w", f.host, err)
		}
		return nil
	})
}

func parseBootstrapFlags(args []string, e env) (bootstrapFlags, error) {
	var f bootstrapFlags
	fs := newFlagSet("bootstrap", e.stderr)
	fs.StringVar(&f.regPath, "registry", "", "registry file (default ~/.config/iormesh/servers.yaml)")
	fs.StringVar(&f.dist, "dist", defaultDist, "directory holding iormesh-linux-<arch> and its "+release.SigSuffix)
	fs.StringVar(&f.keyPath, "key", "", "pinned minisign public key (default ~/.config/iormesh/"+keyFileName+")")
	fs.StringVar(&f.arch, "arch", "", "the host's arch, amd64 or arm64 (default: amd64; -apply reads it from the host)")
	fs.StringVar(&f.user, "user", "", "the SSH user the sudoers rule names (default: HOST's user@ part, "+
		"else your user name — a User in ~/.ssh/config is not seen; -apply reads it from the host)")
	fs.BoolVar(&f.apply, "apply", false, "run the steps over SSH with your own sudo -n instead of printing them")
	if err := fs.Parse(args); err != nil {
		return f, fmt.Errorf("%w: %w", errUsage, err)
	}
	switch {
	case fs.NArg() != 1:
		return f, fmt.Errorf("%w: bootstrap takes exactly one HOST", errUsage)
	case f.arch != "" && f.arch != "amd64" && f.arch != "arm64":
		return f, fmt.Errorf("%w: -arch %q: want amd64 or arm64", errUsage, f.arch)
	case f.user != "" && !hostlayout.ValidUser(f.user):
		return f, fmt.Errorf("%w: -user %q: not a name a sudoers rule may carry", errUsage, f.user)
	}
	f.host = fs.Arg(0)
	return f, nil
}

// bootstrapBundle is what bootstrap installs: the verified build and its
// signature, the pinned key and the rule, each as the bytes staged.
type bootstrapBundle struct {
	// path is the build's local path, name its release name.
	path, name string
	meta       release.Meta
	binary     []byte
	sig        []byte
	key        []byte
	rule       []byte
}

// loadBundle verifies arch's build in dist against the pinned key, read
// once, and pairs it with the key as a minisign key file and user's rule.
func loadBundle(dist, arch, user string, key minisign.PublicKey) (bootstrapBundle, error) {
	p := filepath.Join(dist, release.TracerFile(arch))
	data, sig, m, err := release.ReadVerified(key, p)
	if err != nil {
		return bootstrapBundle{}, fmt.Errorf("local build, nothing pushed: %w", err)
	}
	keyText, err := key.MarshalText()
	if err != nil {
		return bootstrapBundle{}, err
	}
	return bootstrapBundle{path: p, name: release.TracerFile(arch), meta: m, binary: data, sig: sig,
		key: append(keyText, '\n'), rule: []byte(hostlayout.SudoersContent(user))}, nil
}

// bootstrapStep is one step on the host, from the login user's home.
type bootstrapStep struct {
	what string
	argv []string
	// asRoot runs argv under the operator's own sudo: `sudo -n` when
	// applied (no TTY), `sudo` when printed (it may ask a password).
	asRoot bool
}

// bootstrapSteps are the host's steps, printed or applied, for b staged
// in dir.
func bootstrapSteps(b bootstrapBundle, dir string) []bootstrapStep {
	bin := dir + "/" + b.name
	steps := []bootstrapStep{{what: "create " + hostlayout.Root + ", bin/ and etc/, root's 0755", asRoot: true,
		argv: []string{"install", "-d", "-o", "root", "-g", "root", "-m", "0755", hostlayout.Root,
			path.Dir(hostlayout.Binary), path.Dir(hostlayout.Key)}}}
	steps = append(steps, placeSteps("tracer", bin, hostlayout.Binary, "0755", b.binary, false)...)
	steps = append(steps, placeSteps("pinned key", dir+"/"+stagedKey, hostlayout.Key, "0644", b.key, false)...)
	steps = append(steps, bootstrapStep{what: "the installed tracer re-verifies the build against its " +
		"root-owned key and checks the layout (same bytes: a no-op)", asRoot: true,
		argv: []string{hostlayout.Binary, "upgrade", bin}})
	steps = append(steps, placeSteps("sudoers rule", dir+"/"+stagedRule, hostlayout.SudoersFile, "0440",
		b.rule, true)...)
	return append(steps, bootstrapStep{what: "the rule runs the tracer without a password",
		argv: sudoTracer("status")})
}

// placeSteps install staged at dest through a temporary name next to it
// (sudo skips a sudoers.d name with a dot): install root's with mode,
// check the root-owned copy's SHA-256 against data's (and visudo), then
// rename it into place.
func placeSteps(what, staged, dest, mode string, data []byte, visudo bool) []bootstrapStep {
	tmp := path.Dir(dest) + "/." + path.Base(dest) + ".new"
	sum := sha256.Sum256(data)
	steps := []bootstrapStep{
		{what: "install the " + what + " as " + tmp + ", root's " + mode, asRoot: true,
			argv: []string{"install", "-o", "root", "-g", "root", "-m", mode, staged, tmp}},
		{what: "check the installed " + what + "'s SHA-256 against the controller's", asRoot: true,
			argv: []string{"sh", "-c", hashCheck, "sh", tmp, hex.EncodeToString(sum[:])}},
	}
	if visudo {
		steps = append(steps, bootstrapStep{what: "check the rule's syntax", asRoot: true,
			argv: []string{"visudo", "-cf", tmp}})
	}
	return append(steps, bootstrapStep{what: "move the " + what + " into place at " + dest, asRoot: true,
		argv: []string{"mv", "-f", "-T", tmp, dest}})
}

// applyBootstrap runs the steps on the host: preflight, verify, stage,
// then each step in order. A failed step stops it; nothing is undone,
// and until the rule is in place a rerun starts over.
func applyBootstrap(ctx context.Context, e env, f bootstrapFlags, key minisign.PublicKey) error {
	t, err := e.transport(f.host)
	if err != nil {
		return err
	}
	arch, login, err := bootstrapPreflight(ctx, t, f)
	if err != nil {
		return err
	}
	b, err := loadBundle(f.dist, arch, login, key)
	if err != nil {
		return err
	}
	printVerified(e.stdout, b.path, b.meta)
	dir, err := stagingDir(ctx, t)
	if err != nil {
		return err
	}
	if err := pushBundle(ctx, t, dir, b); err != nil {
		return err
	}
	for _, s := range bootstrapSteps(b, dir) {
		argv := s.argv
		if s.asRoot {
			argv = append([]string{"sudo", "-n"}, argv...)
		}
		_, _ = fmt.Fprintf(e.stdout, "%s: %s\n", safe(f.host), safe(s.what))
		out, err := t.Run(ctx, argv...)
		relay(e.stdout, f.host, out)
		if err != nil {
			return fmt.Errorf("%s: %w; stopped here, nothing undone", s.what, err)
		}
	}
	_, _ = fmt.Fprintf(e.stdout, "%s: bootstrapped; iormeshctl deploy %s starts its projects\n", safe(f.host),
		safe(f.host))
	return nil
}

// bootstrapPreflight checks the host before anything is pushed and
// returns its arch and SSH user: the tools deploy needs, the operator's
// sudo without a password, a user name the rule may carry, and no rule
// there yet. A flag naming another arch or user is refused.
func bootstrapPreflight(ctx context.Context, t federate.Transport, f bootstrapFlags) (string, string, error) {
	arch, err := hostArch(ctx, t)
	if err != nil {
		return "", "", err
	}
	if f.arch != "" && f.arch != arch {
		return "", "", fmt.Errorf("-arch %s: the host is %s", f.arch, arch)
	}
	if err := checkTools(ctx, t); err != nil {
		return "", "", err
	}
	if _, err := t.Run(ctx, "sudo", "-n", "true"); err != nil {
		return "", "", fmt.Errorf("sudo -n failed (%w): -apply needs the SSH user's own sudo without a "+
			"password, as ssh runs without a TTY; run the steps `iormeshctl bootstrap %s` prints "+
			"without -apply by hand on a terminal instead", err, f.host)
	}
	out, err := t.Run(ctx, "id", "-un")
	if err != nil {
		return "", "", err
	}
	login := strings.TrimSpace(string(out))
	if !hostlayout.ValidUser(login) {
		return "", "", fmt.Errorf("SSH user name %q: not one a sudoers rule may carry", login)
	}
	if f.user != "" && f.user != login {
		return "", "", fmt.Errorf("-user %s: the SSH user on the host is %s", f.user, login)
	}
	exists, err := remoteTest(ctx, t, "sudo", "-n", "test", "-e", hostlayout.SudoersFile)
	if err != nil {
		return "", "", err
	}
	if exists {
		return "", "", fmt.Errorf("%s already exists: the host is bootstrapped (iormeshctl deploy upgrades "+
			"it) or another rule is there; bootstrap never overwrites one", hostlayout.SudoersFile)
	}
	return arch, login, nil
}

// pushBundle writes b's four files into a private temporary directory
// and pushes them into dir, in one push. The temporary copies go again.
func pushBundle(ctx context.Context, t federate.Transport, dir string, b bootstrapBundle) error {
	tmp, err := os.MkdirTemp("", "iormeshctl-bootstrap-")
	if err != nil {
		return err
	}
	defer func() { _ = os.RemoveAll(tmp) }()
	var files []string
	for _, f := range []struct {
		name string
		data []byte
	}{{b.name, b.binary}, {b.name + release.SigSuffix, b.sig}, {stagedKey, b.key}, {stagedRule, b.rule}} {
		p := filepath.Join(tmp, f.name)
		if err := os.WriteFile(p, f.data, 0o600); err != nil {
			return err
		}
		files = append(files, p)
	}
	return t.Push(ctx, dir, files...)
}

// printBootstrap prints the steps for the host to run by hand, for -arch
// and -user or their defaults, with the verified build's hashes.
func printBootstrap(e env, f bootstrapFlags, key minisign.PublicKey) error {
	arch, login := f.arch, f.user
	if arch == "" {
		arch = defaultBootstrapArch
	}
	if login == "" {
		login = defaultLogin(f.host)
		if !hostlayout.ValidUser(login) {
			return fmt.Errorf("%w: SSH user name %q cannot be named in a sudoers rule: pass -user", errUsage, login)
		}
	}
	b, err := loadBundle(f.dist, arch, login, key)
	if err != nil {
		return err
	}
	for _, l := range bootstrapScript(f.host, login, b) {
		_, _ = fmt.Fprintln(e.stdout, safe(l))
	}
	return nil
}

// defaultLogin is the SSH user the printed rule names without -user: the
// user@ part of a registry host written so (federate's hostName allows
// it), else the controller's own user name, ssh's default login. A User
// set in ~/.ssh/config is not seen: -user names it then.
func defaultLogin(host string) string {
	if u, _, ok := strings.Cut(host, "@"); ok {
		return u
	}
	return localUser()
}

// localUser is the controller's user name.
func localUser() string {
	u, err := user.Current()
	if err != nil {
		return ""
	}
	return u.Username
}

// bootstrapScript is the printed steps: a header naming what was
// verified, the controller's copy, then the host's steps.
func bootstrapScript(host, login string, b bootstrapBundle) []string {
	sum := sha256.Sum256(b.binary)
	remote := host + ":" + stagingRel + "/"
	lines := []string{
		"# iormeshctl bootstrap " + host + ": the first install of the tracer (decision #1 in docs/decisions.md).",
		"# Verified " + b.path + ": " + b.meta.File + " " + b.meta.Version + " against the pinned key, sha256 " +
			hex.EncodeToString(sum[:]) + ".",
		"# The rule names the SSH user " + login + " (-user); the build is for " + b.name + " (-arch).",
		"#",
		"# On the controller:",
		shellLine("ssh", host, "mkdir", "-p", "-m", "0700", stagingRel),
		shellLine("scp", b.path, b.path+release.SigSuffix, remote),
		"#",
		"# On " + host + ", as " + login + ", on a terminal (sudo may ask for your password):",
		printfLine(b.key, printedStaging+"/"+stagedKey),
		printfLine(b.rule, printedStaging+"/"+stagedRule),
	}
	for _, s := range bootstrapSteps(b, printedStaging) {
		argv := s.argv
		if s.asRoot {
			argv = append([]string{"sudo"}, argv...)
		}
		lines = append(lines, "# "+s.what, shellLine(argv...))
	}
	return lines
}

// printfLine is the shell line writing content (whole lines) to file.
func printfLine(content []byte, file string) string {
	args := []string{"printf", `%s\n`}
	args = append(args, strings.Split(strings.TrimSuffix(string(content), "\n"), "\n")...)
	return shellLine(args...) + " > " + file
}

var (
	// shellPlain is an argument the shell takes as it is.
	shellPlain = regexp.MustCompile(`^[A-Za-z0-9_./=:@%+,-]+$`)
	// shellHome is a path under ~ the shell is to expand.
	shellHome = regexp.MustCompile(`^~/[A-Za-z0-9_./-]*$`)
)

// shellLine joins argv into a POSIX shell line, single-quoting every
// argument that is not plain.
func shellLine(argv ...string) string {
	q := make([]string, len(argv))
	for i, a := range argv {
		if shellPlain.MatchString(a) || shellHome.MatchString(a) {
			q[i] = a
		} else {
			q[i] = "'" + strings.ReplaceAll(a, "'", `'\''`) + "'"
		}
	}
	return strings.Join(q, " ")
}
